set -euo pipefail

readonly MAKE_FILE=Makefile
readonly TARGET=$(awk '/^TARGET / {print $3}' $MAKE_FILE)

readonly CONF_FILE=include/config.h

conf_buf='// This file is autogenerated by configure.sh.

#pragma once

'

print_message()
{
    echo -e "\033[0;33;1m$1...\033[0m"
}

print_success()
{
    echo -e "\033[0;32;1m$1!\033[0m"
}

print_error()
{
    echo -e "\033[0;31;1m$1!\033[0m" >&2
}

define()
{
    local macros=$1
    local integer=$2
    local prompt=$3

    local input=""
    local existing=""

    if [[ -f $CONF_FILE ]]; then
        if (( integer != 0 )); then
            existing=$(awk "/^#define $macros / {print \$3}" $CONF_FILE)
        else
            existing=$(awk -F '"' "/^#define $macros / {print \$2}" $CONF_FILE)
        fi
    fi

    while true; do
        read -rsp "$prompt: " input
        echo

        if [[ -z $input ]]; then
            if [[ -z $existing ]]; then
                print_error 'Input is empty'
                continue
            else
                input=$existing
                print_message 'Using existing value'
                break
            fi
        fi

        if (( integer != 0 )) && ! [[ $input =~ ^-?[0-9]+$ ]]; then
            print_error 'Input must be an integer'
            continue
        fi

        break
    done

    if (( integer != 0 )); then
        conf_buf+="#define $macros $input"$'\n'
    else
        conf_buf+="#define $macros \"$input\""$'\n'
    fi
}

print_message "Configuring $TARGET"

define TG_TARGET_CHAT_ID 1 'Telegram target chat ID'
define TG_BOT_API_TOKEN 0 'Telegram bot API token'
define START_DATE 0 'Start date (yyyy-mm-dd)'
echo -n "$conf_buf" > $CONF_FILE

print_success "Configuring $TARGET done"
